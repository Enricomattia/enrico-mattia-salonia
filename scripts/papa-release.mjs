import { createHash } from "node:crypto";
import { readFile, readdir, writeFile } from "node:fs/promises";

// Run before Next builds so the offline bundle matches the deployed assets.
const directory = new URL("../public/papa/", import.meta.url);
const paths = (await readdir(directory, { withFileTypes: true }))
  .filter((entry) => entry.isFile() && entry.name !== "release.js")
  .map((entry) => entry.name)
  .sort();

const files = await Promise.all(paths.map(async (name) => {
  const bytes = await readFile(new URL(name, directory));
  const integrity = "sha256-" + createHash("sha256").update(bytes).digest("base64");
  return { name, integrity };
}));
const version = createHash("sha256").update(JSON.stringify(files)).digest("hex").slice(0, 20);
const assets = files.filter(({ name }) => name !== "index.html" && name !== "sw.js");
const html = await readFile(new URL("index.html", directory), "utf8");
const release = JSON.stringify({ version, assets, html }, null, 2);

await writeFile(new URL("release.js", directory),
  "// Generated by scripts/papa-release.mjs.\n" +
  `globalThis.PAPA_RELEASE = ${release};\n`
);
console.log(`Saggezza ${version}`);
